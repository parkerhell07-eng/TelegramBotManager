package com.telegrambot.manager.data.cloud

import com.google.gson.Gson
import com.google.gson.GsonBuilder

/**
 * Builds the Cloudflare Worker JavaScript that becomes the bot's cloud brain.
 *
 * The generated module worker:
 *  - verifies the Telegram secret token header (nobody else can call it),
 *  - mirrors the phone engine's reply logic: /start welcome, built-in
 *    help/id/about, custom commands, keywords in private chats, unknown
 *    command fallback, with the same {name}/{username}/{chat_id}/{bot_name}
 *    placeholders,
 *  - forwards every user message to the owner's private chat (support inbox
 *    inside Telegram),
 *  - lets the owner answer a user by replying to the forwarded message —
 *    the reply is delivered to the user as the bot.
 *
 * The template avoids Kotlin string templates entirely; configuration is
 * injected by replacing placeholder markers at build time.
 */
object WorkerBuilder {

    data class WRule(val command: String = "", val reply: String = "")
    data class WKeyword(val keyword: String = "", val reply: String = "")

    data class WConfig(
        val botName: String,
        val botUsername: String,
        val defaultName: String,
        val welcomeEnabled: Boolean,
        val welcomeText: String,
        val unknownText: String,
        val helpText: String,
        val idText: String,
        val aboutText: String,
        val commands: List<WRule>,
        val keywords: List<WKeyword>,
        val admin: Long,
        val forward: Boolean,
        val forwardHeader: String,
        val forwardFrom: String,
        val relayPrefix: String,
        val hintReply: String
    )

    private val gson: Gson = GsonBuilder().disableHtmlEscaping().create()

    fun build(cfg: WConfig, secret: String, botToken: String): String {
        val cfgJson = gson.toJson(cfg)
        val secretJson = gson.toJson(secret)
        val tokenJson = gson.toJson(botToken)
        return TEMPLATE
            .replace("@@SECRET@@", secretJson)
            .replace("@@TOKEN@@", tokenJson)
            .replace("@@CFG@@", cfgJson)
    }

    private val TEMPLATE = """
// Auto-generated by Telegram Bot Manager — do not edit by hand.
const SECRET = @@SECRET@@;
const TOKEN = @@TOKEN@@;
const CFG = @@CFG@@;

export default {
  async fetch(request) {
    if (request.method !== "POST") return ok();
    if (request.headers.get("X-Telegram-Bot-Api-Secret-Token") !== SECRET) {
      return new Response("forbidden", { status: 403 });
    }
    let update;
    try {
      update = await request.json();
    } catch (e) {
      return ok();
    }
    try {
      await handle(update);
    } catch (e) {
      // one bad update must never break the webhook contract
    }
    return ok();
  }
};

function ok() {
  return new Response("ok");
}

async function api(method, body) {
  const r = await fetch("https://api.telegram.org/bot" + TOKEN + "/" + method, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body)
  });
  return r.json();
}

function fill(tpl, msg) {
  const from = msg.from || {};
  const name = from.first_name || CFG.defaultName;
  const user = from.username ? "@" + from.username : "";
  return tpl.split("{name}").join(name)
    .split("{username}").join(user)
    .split("{chat_id}").join(String(msg.chat.id))
    .split("{bot_name}").join(CFG.botName);
}

async function handle(update) {
  const msg = update.message;
  if (!msg || !msg.text) return;
  const from = msg.from;
  if (from && from.is_bot) return;
  const chat = msg.chat;
  const text = msg.text.trim();
  const isGroup = chat.type === "group" || chat.type === "supergroup" || chat.type === "channel";

  // Owner path: reply to a forwarded message delivers to that user as the bot.
  if (from && CFG.admin && from.id === CFG.admin) {
    if (msg.reply_to_message) {
      const rt = msg.reply_to_message;
      let dest = 0;
      if (rt.forward_from && rt.forward_from.id) dest = rt.forward_from.id;
      if (dest) {
        await api("sendMessage", { chat_id: dest, text: CFG.relayPrefix + text });
      } else {
        await api("sendMessage", { chat_id: CFG.admin, text: CFG.hintReply });
      }
    }
    return;
  }

  let reply = null;
  if (text.startsWith("/")) {
    const head = text.slice(1).split(" ")[0] || "";
    const target = (head.split("@")[0] || "").toLowerCase();
    const mention = head.indexOf("@") >= 0 ? head.split("@")[1].toLowerCase() : "";
    if (!isGroup || !mention || mention === (CFG.botUsername || "").toLowerCase()) {
      if (target === "start") {
        if (CFG.welcomeEnabled && CFG.welcomeText) reply = fill(CFG.welcomeText, msg);
      } else if (target === "help") {
        reply = fill(CFG.helpText, msg);
      } else if (target === "id") {
        reply = fill(CFG.idText, msg);
      } else if (target === "about") {
        reply = fill(CFG.aboutText, msg);
      } else {
        let hit = null;
        const cmds = CFG.commands || [];
        for (let i = 0; i < cmds.length; i++) {
          const c = (cmds[i].command || "").replace("/", "").toLowerCase();
          if (c === target && cmds[i].reply) {
            hit = cmds[i];
            break;
          }
        }
        if (hit) reply = fill(hit.reply, msg);
        else if (CFG.unknownText) reply = fill(CFG.unknownText, msg);
      }
    }
  } else if (!isGroup) {
    const lower = text.toLowerCase();
    const kws = CFG.keywords || [];
    for (let i = 0; i < kws.length; i++) {
      const key = (kws[i].keyword || "").trim().toLowerCase();
      if (key && lower.indexOf(key) >= 0 && kws[i].reply) {
        reply = fill(kws[i].reply, msg);
        break;
      }
    }
  }

  if (reply) {
    await api("sendMessage", { chat_id: chat.id, text: reply });
  }

  // Support inbox: copy every user message into the owner's private chat.
  if (CFG.forward && CFG.admin) {
    const who = ((from && from.first_name) || "") + (from && from.last_name ? " " + from.last_name : "");
    const uname = from && from.username ? " (@" + from.username + ")" : "";
    const label = ((who + uname).trim()) || chat.title || ("chat " + chat.id);
    const body = CFG.forwardHeader + "\n" + CFG.forwardFrom + ": " + label + "\nchat_id: " + chat.id + "\n\n" + text;
    await api("sendMessage", { chat_id: CFG.admin, text: body, disable_notification: true });
  }
}
""".trim()
}
