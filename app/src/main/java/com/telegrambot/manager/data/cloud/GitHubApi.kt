package com.telegrambot.manager.data.cloud

import android.util.Base64
import com.google.gson.JsonObject
import com.google.gson.JsonParser
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import java.util.concurrent.TimeUnit

/**
 * Minimal GitHub REST API client (OkHttp) covering everything the in-app
 * cloud engine needs: token validation, repo creation, file upload (contents
 * API), Actions secret (libsodium sealed box via [GitHubSecrets]), workflow
 * dispatch and liveness reads.
 *
 * All calls are BLOCKING — run them on Dispatchers.IO (CloudDeployer does).
 */
class GitHubApi(private val pat: String) {

    private val http = OkHttpClient.Builder()
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(40, TimeUnit.SECONDS)
        .build()

    private val json = "application/json".toMediaType()

    // ── Result type ──────────────────────────────────────────────────────

    sealed class Res {
        class Ok(val body: JsonObject?) : Res()
        class Err(val code: Int, val message: String) : Res()
    }

    private fun call(request: Request): Res {
        val resp = try {
            http.newCall(request).execute()
        } catch (e: Exception) {
            return Res.Err(0, e.message ?: "network error")
        }
        resp.use { r ->
            val text = try {
                r.body?.string() ?: ""
            } catch (e: Exception) {
                ""
            }
            val obj = if (text.isNotBlank()) try {
                JsonParser.parseString(text).asJsonObject
            } catch (e: Exception) {
                null
            } else null
            if (r.isSuccessful) return Res.Ok(obj)
            val msg = obj?.get("message")?.asString ?: ("HTTP " + r.code)
            return Res.Err(r.code, msg)
        }
    }

    private fun req(url: String, method: String, payload: String? = null): Request {
        val b = Request.Builder()
            .url(url)
            .header("Authorization", "Bearer $pat")
            .header("Accept", "application/vnd.github+json")
            .header("X-GitHub-Api-Version", "2022-11-28")
            .header("User-Agent", "TelegramBotManager-App")
        return when (method) {
            "GET" -> b.get().build()
            "DELETE" -> b.delete().build()
            "PUT" -> b.put((payload ?: "{}").toRequestBody(json)).build()
            "POST" -> b.post((payload ?: "{}").toRequestBody(json)).build()
            "PATCH" -> b.patch((payload ?: "{}").toRequestBody(json)).build()
            else -> b.get().build()
        }
    }

    // ── High-level operations ────────────────────────────────────────────

    /** Validates the PAT; returns the GitHub login it belongs to. */
    fun me(): Pair<Boolean, String> {
        return when (val r = call(req("$API/user", "GET"))) {
            is Res.Ok -> {
                val login = r.body?.get("login")?.asString ?: "?"
                true to login
            }
            is Res.Err -> false to (if (r.code == 401) "invalid token" else r.message)
        }
    }

    /** Creates a public repo (public ⇒ unlimited free Actions minutes + cron). */
    fun createRepo(name: String): Res =
        call(
            req(
                "$API/user/repos", "POST",
                JsonObject().apply {
                    addProperty("name", name)
                    addProperty("private", false)
                    addProperty("auto_init", true)
                    addProperty("has_issues", false)
                    addProperty("has_wiki", false)
                    addProperty("has_projects", false)
                    addProperty(
                        "description",
                        "24/7 Telegram bot engine generated by TelegramBotManager app"
                    )
                }.toString()
            )
        )

    fun deleteRepo(owner: String, repo: String): Res =
        call(req("$API/repos/$owner/$repo", "DELETE"))

    /** Creates or updates a file on the default branch. */
    fun putFile(owner: String, repo: String, path: String, content: ByteArray, message: String): Res {
        // Existing file? → need its sha to update.
        var sha: String? = null
        when (val cur = call(req("$API/repos/$owner/$repo/contents/$path", "GET"))) {
            is Res.Ok -> sha = cur.body?.get("sha")?.asString
            is Res.Err -> if (cur.code != 404) return cur
        }
        val payload = JsonObject().apply {
            addProperty("message", message)
            addProperty(
                "content",
                Base64.encodeToString(content, Base64.NO_WRAP)
            )
            addProperty("branch", "main")
            if (sha != null) addProperty("sha", sha)
        }
        return call(req("$API/repos/$owner/$repo/contents/$path", "PUT", payload.toString()))
    }

    /** Fetches a file's raw bytes (null if missing). */
    fun getFile(owner: String, repo: String, path: String): ByteArray? {
        val r = call(req("$API/repos/$owner/$repo/contents/$path?ref=main", "GET"))
        if (r !is Res.Ok) return null
        val b64 = r.body?.get("content")?.asString ?: return null
        return try {
            Base64.decode(b64.replace("\n", "").replace("\r", ""), Base64.NO_WRAP)
        } catch (e: Exception) {
            null
        }
    }

    /** Reads the repo public key for secret encryption → (keyId, keyB64) or error text. */
    fun secretKey(owner: String, repo: String): Pair<String?, String?> {
        return when (val r = call(req("$API/repos/$owner/$repo/actions/secrets/public-key", "GET"))) {
            is Res.Ok -> {
                val id = r.body?.get("key_id")?.asString
                val key = r.body?.get("key")?.asString
                if (id != null && key != null) id to key else null to "malformed public-key response"
            }
            is Res.Err -> null to r.message
        }
    }

    /** Creates/updates the BOT_TOKEN Actions secret (sealed with [GitHubSecrets]). */
    fun putSecret(owner: String, repo: String, name: String, value: String): Pair<Boolean, String> {
        val (keyId, keyB64) = secretKey(owner, repo)
        if (keyId == null || keyB64 == null) return false to (keyB64 ?: "no public key")
        val encrypted = try {
            GitHubSecrets.seal(keyB64, value.toByteArray(Charsets.UTF_8))
        } catch (e: Exception) {
            return false to ("seal failed: " + (e.message ?: "?"))
        }
        val payload = JsonObject().apply {
            addProperty("encrypted_value", encrypted)
            addProperty("key_id", keyId)
        }
        return when (val r = call(req("$API/repos/$owner/$repo/actions/secrets/$name", "PUT", payload.toString()))) {
            is Res.Ok -> true to "stored"
            is Res.Err -> false to r.message
        }
    }

    /** Triggers the engine workflow immediately (used for setup + manual checks). */
    fun dispatch(owner: String, repo: String): Pair<Boolean, String> {
        val payload = JsonObject().apply {
            addProperty("ref", "main")
            add("inputs", JsonObject())
        }
        return when (val r = call(req("$API/repos/$owner/$repo/actions/workflows/engine.yml/dispatches", "POST", payload.toString()))) {
            is Res.Ok -> true to "dispatched"
            is Res.Err -> false to r.message
        }
    }

    companion object {
        private const val API = "https://api.github.com"

        /** Sanitizes a bot name into a valid repo slug. */
        fun repoSlug(botName: String, suffix: String): String {
            val ascii = botName.map { c -> if (c in 'a'..'z' || c in 'A'..'Z' || c in '0'..'9') c else '-' }
                .joinToString("")
                .trim('-')
                .lowercase()
                .take(24)
            val base = if (ascii.isBlank()) "bot" else ascii
            return "tbm-$base-$suffix"
        }
    }
}
